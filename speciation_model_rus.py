path="path_to_directories_for_saving_calculation_result"

Lpm=np.arange(0.01, 0.21, 0.01) #задаем вектор  значений вероятностей занятие новой ниши (вероятности видовой дивергенции) в единицу времени
dt=0.1 #задаем шаг интегрирования для метода Эйлера с пересчетом

#запуск алгоритм исследования системы с анализом для вех комбинаций вероятностей переходов Lpm и количества экологических ниш, меняющихся в диапазоне от 2 до 15
for i in range(0, len(Lpm)): #внешний цикл перебора вероятностей
  for j in range(2, 16): #внутренний цикл перебора количества экологических ниш
    n_niches=j #задание значение для параметра количества экологических ниш
    Lp=Lpm[i] #задание значение для параметра вероятностей видовой дивергенции
    df_pvalue=integrate_eil_per(n_niches, Lp, dt) #запуск интегрирования
